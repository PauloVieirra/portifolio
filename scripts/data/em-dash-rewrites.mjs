export const removeEmDashes = (s) => {
  let out = REWRITES.reduce((acc, [from, to]) => acc.split(from).join(to), s);
  out = out.replace(/\*\* — /g, '**: ');                          // "* **Termo** — texto" → "* **Termo**: texto"
  out = out.replace(/(\d{4}) — (\d{4}|hoje)/g, '$1 - $2');         // "2021 — 2022", "2025 — hoje"
  return out;
};
